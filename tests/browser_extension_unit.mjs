import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const code = await readFile(new URL('../browser-extension/model.js', import.meta.url), 'utf8');
const context = vm.createContext({ URL, Error, Set, Number, String }); vm.runInContext(code, context);
const M = context.ProxyModel;
const fixture = { version: 1, nodes: [{ id: 'sg', name: 'Singapore', scheme: 'https', host: 'proxy.example.com', port: 8443, username: 'fixture', password: 'fixture-only-password' }] };
assert.equal(M.parse(fixture).length, 1);
assert.equal(new URL(M.subscriptionUrl('https://example.com/subscribe/test?target=raw')).searchParams.get('target'), 'browser');
for (const node of [{...fixture.nodes[0],scheme:'http'},{...fixture.nodes[0],host:'127.0.0.1'},{...fixture.nodes[0],password:''},{...fixture.nodes[0],port:0}]) assert.throws(()=>M.parse({version:1,nodes:[node]}));
assert.equal(M.config(fixture.nodes[0]).rules.singleProxy.scheme, 'https');
assert.deepEqual([...M.config(fixture.nodes[0]).rules.bypassList], ['<-loopback>']);
assert.ok(M.types.includes('main_frame'));
const manifest = JSON.parse(await readFile(new URL('../browser-extension/manifest.json', import.meta.url), 'utf8'));
assert.ok(!manifest.permissions.includes('nativeMessaging'));
assert.ok(manifest.permissions.includes('webRequestAuthProvider'));
const rules = JSON.parse(await readFile(new URL('../browser-extension/lockdown.json', import.meta.url), 'utf8'));
assert.ok(rules.some(r => r.action.type === 'block' && r.condition.resourceTypes.includes('main_frame')));
assert.ok(rules.some(r => r.priority > 2 && r.condition.resourceTypes.includes('webtransport')));
console.log('PASS Pure-extension subscription validation, TLS-only proxies, startup/page/WebTransport blocks and no native host permission');
